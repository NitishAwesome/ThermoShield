export function getMunicipalCorporationById(id: string): MunicipalCorporationInfo | undefined {
  if (!id) return undefined;
  const match = INDIAN_MUNICIPAL_CORPORATIONS.find((c) => c.id.toLowerCase() === id.toLowerCase());
  if (match) return match;
  return INDIAN_MUNICIPAL_CORPORATIONS.find((c) => c.shortCode.toLowerCase() === id.toLowerCase());
}

export function findMunicipalCorporationByCity(cityName: string): MunicipalCorporationInfo | undefined {
  if (!cityName) return undefined;
  const norm = cityName.toLowerCase().trim();
  return INDIAN_MUNICIPAL_CORPORATIONS.find(
    (c) => norm.includes(c.city.toLowerCase()) || c.city.toLowerCase().includes(norm)
  );
}
