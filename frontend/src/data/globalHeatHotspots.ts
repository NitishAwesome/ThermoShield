// Helper: Filter stations by region
export const getStationsByRegion = (regionId: string): GlobalHeatStation[] => {
  if (!regionId || regionId === 'all') return GLOBAL_HEAT_STATIONS;
  const match = GLOBAL_REGIONS.find((r) => r.id === regionId);
  if (!match) return GLOBAL_HEAT_STATIONS;
  return GLOBAL_HEAT_STATIONS.filter((s) => s.region.toLowerCase().includes(match.shortName.toLowerCase()) || s.region === match.name);
};

